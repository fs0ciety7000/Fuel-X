// Typed asset wrappers (ADR 0007 stage 4, ASSETS_GUIDE §7) → src/render/assets/generated/<file>.ts + index.ts.
// Pure string generation; build.ts formats with prettier and writes the files.
import { effectiveDrawCalls } from './contract.ts';
import type { AssetContract, GlbSummary } from './contract.ts';

export interface CodegenInput {
  contract: AssetContract;
  summaries: GlbSummary[];
  /** sha256 hex of each optimized LOD file (cache-busting `?v=` query). */
  hashes: string[];
}

const HEADER = '// Generated by scripts/assets/codegen.ts (npm run asset). Do not edit by hand.';

export function constName(file: string): string {
  return file.toUpperCase();
}

export function typePrefix(file: string): string {
  return file
    .split('_')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}

export function lodUrl(file: string, lod: number, hash: string): string {
  return `/models/${file}${lod === 0 ? '' : `_lod${lod}`}.glb?v=${hash.slice(0, 8)}`;
}

/** `TOWER_ArmL` → `ArmL`, `SOCKET_CatchPointL` → `CatchPointL`. */
export function shortKey(asset: string, name: string): string {
  if (name.startsWith('SOCKET_')) return name.slice('SOCKET_'.length);
  if (name.startsWith(`${asset}_`)) return name.slice(asset.length + 1);
  return name;
}

const lit = (v: string): string => `'${v}'`;

export function generateAsset({ contract: c, summaries, hashes }: CodegenInput): string {
  const C = constName(c.file);
  const T = typePrefix(c.file);
  const lod0 = summaries[0];
  if (!lod0) throw new Error(`${c.file}: no LOD0 summary`);
  const urls = summaries.map((s, i) => lodUrl(c.file, s.lod, hashes[i] ?? ''));
  const nodes = c.nodes.map((n) => `${shortKey(c.asset, n)}: ${lit(n)}`).join(', ');
  const sockets = c.sockets.map((n) => `${shortKey(c.asset, n)}: ${lit(n)}`).join(', ');
  const anim = Object.entries(c.anim)
    .map(
      ([n, a]) =>
        `${shortKey(c.asset, n)}: { node: ${lit(n)}, kind: ${lit(a.kind)}, axis: ${lit(a.axis)}, ` +
        `min: ${a.min}, max: ${a.max}, rest: ${a.rest}, unit: ${lit(a.unit)} }`,
    )
    .join(', ');
  const b = lod0.bounds;
  // Only for contracts that opt into instancing: node groups sharing one mesh → one InstancedMesh each.
  const instanced = c.instanceLinked
    ? `\n  instanced: [${lod0.sharedMeshes.map((g) => `[${g.map(lit).join(', ')}]`).join(', ')}],`
    : '';
  return `${HEADER}
// Source: blender/assets/${c.file}.py + ${c.file}.contract.json. Bounds in three (Y-up) metres at rest pose.
export const ${C} = {
  name: ${lit(c.file)},
  asset: ${lit(c.asset)},
  url: ${lit(urls[0] ?? '')},
  lods: [${urls
    .slice(1)
    .map((u) => lit(u))
    .join(', ')}],
  nodes: { ${nodes} },
  sockets: { ${sockets} },
  anim: { ${anim} },
  bounds: { min: [${b.min.join(', ')}], max: [${b.max.join(', ')}] },
  triangles: [${summaries.map((s) => s.triangles).join(', ')}],
  bytes: [${summaries.map((s) => s.bytes).join(', ')}],
  drawCalls: ${effectiveDrawCalls(c, lod0)},${instanced}
} as const;

export type ${T}Node = (typeof ${C}.nodes)[keyof typeof ${C}.nodes];
export type ${T}Socket = (typeof ${C}.sockets)[keyof typeof ${C}.sockets];
`;
}

export function generateIndex(files: string[]): string {
  const sorted = [...files].sort();
  const imports = sorted.map((f) => `import { ${constName(f)} } from './${f}.ts';`).join('\n');
  const entries = sorted.map((f) => `${f}: ${constName(f)}`).join(', ');
  const reexports = sorted.map((f) => `export * from './${f}.ts';`).join('\n');
  return `${HEADER}
${imports}

${reexports}

export const ASSETS = { ${entries} } as const;

export type AssetName = keyof typeof ASSETS;
export type AssetNode<N extends AssetName> = (typeof ASSETS)[N]['nodes'][keyof (typeof ASSETS)[N]['nodes']];
export type AssetSocket<N extends AssetName> = (typeof ASSETS)[N]['sockets'][keyof (typeof ASSETS)[N]['sockets']];
`;
}
